// Writes src/app/icons.js: every Phosphor icon name the UI's code mentions, with its regular-weight path data taken
// from @phosphor-icons/react (the same glyph as the font), so lib.jsx can draw it as SVG that draws itself on and
// morphs. Only the paths: the components would carry all six weights. Run it after adding icons: node scripts/icons.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const defs = path.join(root, 'node_modules/@phosphor-icons/react/dist/defs');
const pascal = (n) => n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const names = new Set();
const walk = (d) => { for (const f of readdirSync(d)) { const p = path.join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.jsx$/.test(f)) for (const m of readFileSync(p, 'utf8').matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) names.add(m[1]); } };
walk(path.join(root, 'src', 'app'));
const out = {};
for (const n of [...names].sort()) {
  const f = path.join(defs, `${pascal(n)}.es.js`);
  if (!existsSync(f)) continue;
  const src = readFileSync(f, 'utf8'), at = src.indexOf('"regular"');
  const part = src.slice(at, src.indexOf('\n  ]', at));
  const d = [...part.matchAll(/"path",\s*\{\s*d:\s*"([^"]+)"\s*\}/g)].map((m) => m[1]);
  if (d.length && !/createElement\("(?!path)/.test(part.replace(/createElement\([a-z]\.Fragment/g, ''))) out[n] = d.join(' '); // only icons drawn wholly as paths
}
writeFileSync(path.join(root, 'src/app/icons.js'), [
  '// Generated by scripts/icons.mjs from the icon names the UI uses: each Phosphor glyph\'s regular-weight path, drawn as',
  '// SVG by lib.jsx so it can draw itself on and morph. A name not here falls back to the Phosphor font.',
  `export const SVG = ${JSON.stringify(out)};`, ''].join('\n'));
console.log(`${Object.keys(out).length} icons, ${Math.round(JSON.stringify(out).length / 1024)} KB`);
